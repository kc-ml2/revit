"""Structured regular-field convolutions for finite cyclic/dihedral groups.

ESCNN layout is [B, fields * group_order, H, W]. Spatial depthwise kernels
are generated by trivial->regular ESCNN lifting bases, then applied to the
matching orientation channels. Group-axis maps commute with the left regular
action: fixed-support right translations (linear) or full right convolution
implemented by real FFTs (Fourier). No dense group-by-group matrix is expanded.
"""

import math

import numpy as np
import torch
from torch import nn
from torch.nn import functional as F
from escnn.group import CyclicGroup, DihedralGroup
from escnn.nn import FieldType, GeometricTensor, R2Conv


_LAYOUT_CACHE = {}


def regular_layout(group):
    """Map canonical (reflection, rotation) coordinates to ESCNN fiber order.

    Derive coordinates from the actual representation action on a basis vector
    rather than assuming a particular ordering of ESCNN's regular channels.
    Returned tensors are immutable CPU setup data, not dense runtime operators.
    """
    key = id(group)
    if key in _LAYOUT_CACHE:
        return _LAYOUT_CACHE[key]
    if isinstance(group, DihedralGroup):
        branches, rotations = 2, group.order() // 2
        elements = [group.element((s, k)) for s in range(2) for k in range(rotations)]
    elif isinstance(group, CyclicGroup):
        branches, rotations = 1, group.order()
        elements = [group.element(k) for k in range(rotations)]
    else:
        raise ValueError("Structured operators support finite CyclicGroup and DihedralGroup only")
    indices = []
    for element in elements:
        column = group.regular_representation(element)[:, 0]
        index = int(column.argmax())
        if not np.allclose(column, np.eye(group.order())[:, index], atol=1e-6):
            raise ValueError("Expected a permutation-basis regular representation")
        indices.append(index)
    if len(set(indices)) != group.order():
        raise ValueError("Regular representation coordinates must be a bijection")
    indices = torch.tensor(indices, dtype=torch.long)
    layout = branches, rotations, tuple(elements), indices, indices.argsort()
    _LAYOUT_CACHE[key] = layout
    return layout


def regular_fields(in_type, out_type):
    if in_type.gspace != out_type.gspace:
        raise ValueError("Input and output must use the same gspace")
    for ft in (in_type, out_type):
        if not ft.representations or any(r != ft.gspace.regular_repr for r in ft.representations):
            raise ValueError("Structured convolutions require complete regular fields")
    return len(in_type.representations), len(out_type.representations)


class EquivariantSpatialDepthwise(nn.Module):
    """Orientation-tied spatial filtering with O(g * fields * k^2) MACs.

    The lifting kernel generator is only a parameter/basis container. Its own
    convolution is never run: each generated orientation kernel filters its
    corresponding regular-channel input using depthwise conv2d.
    """

    def __init__(self, in_type, kernel_size, stride=1, initialize=True):
        super().__init__()
        if kernel_size <= 0 or kernel_size % 2 != 1 or stride <= 0:
            raise ValueError("Positive odd kernel size and positive stride required")
        self.in_type = self.out_type = in_type
        self.kernel_size, self.stride = kernel_size, stride
        self.padding = kernel_size // 2
        fields = len(in_type.representations)
        self.kernel_generator = R2Conv(
            FieldType(in_type.gspace, fields * [in_type.gspace.trivial_repr]),
            in_type, kernel_size, padding=self.padding, groups=fields,
            bias=False, initialize=initialize,
        )

    def forward(self, x):
        if x.type != self.in_type:
            raise ValueError("Incorrect spatial depthwise input type")
        generator = self.kernel_generator
        kernel = generator.expand_parameters()[0] if self.training else generator.filter
        output = F.conv2d(x.tensor, kernel, stride=self.stride, padding=self.padding,
                          groups=self.in_type.size)
        return GeometricTensor(output, self.out_type)


class SharedFieldLinear(nn.Module):
    """The same channel matrix at every orientation and spatial position."""

    def __init__(self, in_type, out_type):
        super().__init__()
        self.in_fields, self.out_fields = regular_fields(in_type, out_type)
        self.in_type, self.out_type = in_type, out_type
        self.order = in_type.gspace.fibergroup.order()
        self.weight = nn.Parameter(torch.empty(self.out_fields, self.in_fields))
        nn.init.kaiming_uniform_(self.weight, a=math.sqrt(5))

    def forward(self, x):
        if x.type != self.in_type:
            raise ValueError("Incorrect shared-field input type")
        b, _, h, w = x.tensor.shape
        # A 1x1 conv mixes fields only; orientations are part of the spatial
        # batch of positions. It never expands a (g*d_out)x(g*d_in) weight.
        tensor = x.tensor.reshape(b, self.in_fields, self.order * h, w)
        output = F.conv2d(tensor, self.weight[:, :, None, None])
        return GeometricTensor(output.reshape(b, self.out_fields * self.order, h, w), self.out_type)


class SparseRightGroupMix(nn.Module):
    """Per-field mixing over <=4 right translations, equivariant to the left action."""

    def __init__(self, in_type):
        super().__init__()
        regular_fields(in_type, in_type)
        self.in_type = self.out_type = in_type
        self.fields = len(in_type.representations)
        group = in_type.gspace.fibergroup
        self.order = group.order()
        _, _, elements, to_canonical, _ = regular_layout(group)
        # Identity first for a stable identity initialization. Include inverse
        # rotation and reflection generators, deduplicating small-group cases.
        neighbors = [group.identity]
        for generator in group.generators:
            for element in (generator, ~generator):
                if element not in neighbors:
                    neighbors.append(element)
        indices = {element: int(to_canonical[i]) for i, element in enumerate(elements)}
        right = torch.empty(len(neighbors), self.order, dtype=torch.long)
        for j, neighbor in enumerate(neighbors):
            for element in elements:
                right[j, indices[element]] = indices[element @ neighbor]
        self.register_buffer("right_indices", right, persistent=False)
        self.weight = nn.Parameter(torch.zeros(self.fields, len(neighbors)))
        with torch.no_grad():
            self.weight[:, 0] = 1.0

    def forward(self, x):
        if x.type != self.in_type:
            raise ValueError("Incorrect sparse-group input type")
        b, _, h, w = x.tensor.shape
        values = x.tensor.reshape(b, self.fields, self.order, h, w)
        output = None
        # Do not gather every neighbor into one large activation tensor.
        for j in range(self.right_indices.size(0)):
            weight = self.weight[:, j].to(values.dtype)[None, :, None, None, None]
            term = values.index_select(2, self.right_indices[j]) * weight
            output = term if output is None else output + term
        return GeometricTensor(output.reshape(b, self.fields * self.order, h, w), self.out_type)


class FourierRightGroupLinear(nn.Module):
    """Full regular-field right convolution, evaluated with cyclic FFT blocks.

    Parameters are real W[out_field,in_field,reflection,rotation]. For D_N,
    y_0 = corr(x_0,W_0)+corr(x_1,W_1), while
    y_1 = conv(x_1,W_0)+conv(x_0,W_1). This implements D_N, not C_(2N).
    Real FFTs run in FP32 under AMP (FP64 when explicitly requested), and
    results are cast back to the feature dtype. All N are supported, including
    odd N and non-power-of-two N; inverse transforms always specify n=N.
    """

    def __init__(self, in_type, out_type):
        super().__init__()
        self.in_fields, self.out_fields = regular_fields(in_type, out_type)
        self.in_type, self.out_type = in_type, out_type
        group = in_type.gspace.fibergroup
        self.order = group.order()
        branches, rotations, _, to_canonical, from_canonical = regular_layout(group)
        self.branches, self.rotations = branches, rotations
        self.register_buffer("to_canonical", to_canonical.clone(), persistent=False)
        self.register_buffer("from_canonical", from_canonical.clone(), persistent=False)
        self.weight = nn.Parameter(torch.empty(self.out_fields, self.in_fields, branches, rotations))
        nn.init.normal_(self.weight, std=1 / math.sqrt(self.in_fields * self.order))

    def forward(self, x):
        if x.type != self.in_type:
            raise ValueError("Incorrect Fourier input type")
        b, _, h, w = x.tensor.shape
        input_dtype = x.tensor.dtype
        dtype = torch.float64 if input_dtype == torch.float64 else torch.float32
        with torch.autocast(device_type=x.tensor.device.type, enabled=False):
            values = x.tensor.reshape(b, self.in_fields, self.order, h, w)
            values = values.index_select(2, self.to_canonical).to(dtype)
            values = values.reshape(b, self.in_fields, self.branches, self.rotations, h, w)
            # FFT along a contiguous last axis, rather than striding across
            # entire HxW planes. This matters for the very short group FFTs.
            values = values.permute(0, 1, 2, 4, 5, 3).contiguous()
            spectrum = torch.fft.rfft(values, dim=-1)
            kernel = torch.fft.rfft(self.weight.to(dtype), dim=-1)
            y0 = torch.einsum("bihwf,oif->bohwf", spectrum[:, :, 0], kernel[:, :, 0].conj())
            if self.branches == 2:
                y0 = y0 + torch.einsum("bihwf,oif->bohwf", spectrum[:, :, 1], kernel[:, :, 1].conj())
                y1 = (torch.einsum("bihwf,oif->bohwf", spectrum[:, :, 1], kernel[:, :, 0])
                      + torch.einsum("bihwf,oif->bohwf", spectrum[:, :, 0], kernel[:, :, 1]))
                output_spectrum = torch.stack((y0, y1), dim=2)
            else:
                output_spectrum = y0.unsqueeze(2)
            output = torch.fft.irfft(output_spectrum, n=self.rotations, dim=-1)
            output = output.permute(0, 1, 2, 5, 3, 4).contiguous()
            output = output.reshape(b, self.out_fields, self.order, h, w)
            output = output.index_select(2, self.from_canonical).reshape(b, self.out_fields * self.order, h, w)
        return GeometricTensor(output.to(input_dtype), self.out_type)


class LinearRegularConv(nn.Module):
    """Spatial depthwise -> shared field matrix -> sparse right-group mix."""

    def __init__(self, in_type, out_type, kernel_size=1, stride=1, initialize=True):
        super().__init__()
        regular_fields(in_type, out_type)
        self.in_type, self.out_type = in_type, out_type
        self.kernel_size, self.stride, self.padding = kernel_size, stride, kernel_size // 2
        self.spatial = (EquivariantSpatialDepthwise(in_type, kernel_size, stride, initialize)
                        if kernel_size != 1 or stride != 1 else nn.Identity())
        self.fields = SharedFieldLinear(in_type, out_type)
        self.group_mix = SparseRightGroupMix(out_type)

    def forward(self, x):
        return self.group_mix(self.fields(self.spatial(x)))


class FourierRegularConv(nn.Module):
    """Spatial depthwise -> full Fourier right-group field mixing."""

    def __init__(self, in_type, out_type, kernel_size=1, stride=1, initialize=True):
        super().__init__()
        regular_fields(in_type, out_type)
        self.in_type, self.out_type = in_type, out_type
        self.kernel_size, self.stride, self.padding = kernel_size, stride, kernel_size // 2
        self.spatial = (EquivariantSpatialDepthwise(in_type, kernel_size, stride, initialize)
                        if kernel_size != 1 or stride != 1 else nn.Identity())
        self.group_mix = FourierRightGroupLinear(in_type, out_type)

    def forward(self, x):
        return self.group_mix(self.spatial(x))


def regular_conv(in_type, out_type, kernel_size=1, stride=1, initialize=True, mode="quadratic"):
    """Factory keeps the original quadratic R2Conv checkpoint layout unchanged."""
    if mode == "quadratic":
        return R2Conv(in_type, out_type, kernel_size, stride=stride, padding=kernel_size // 2,
                      bias=False, initialize=initialize)
    if mode == "linear":
        return LinearRegularConv(in_type, out_type, kernel_size, stride, initialize)
    if mode == "fourier":
        return FourierRegularConv(in_type, out_type, kernel_size, stride, initialize)
    raise ValueError(f"Unknown regular convolution mode: {mode}")
